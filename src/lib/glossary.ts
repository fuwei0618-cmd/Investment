// 長的名詞先比對，避免「本益比標準差」被切成「本益比」。
const TERMS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);

export type TermPart = string | { term: string; text: string };

// 把一段文字切成「一般文字」和「名詞」；每個名詞在同一段只標第一次。
export function findTerms(text: string): TermPart[] {
  const parts: TermPart[] = [];
  const seen = new Set<string>();
  let i = 0;
  let buf = "";
  while (i < text.length) {
    const hit = TERMS.find((t) => !seen.has(t) && text.startsWith(t, i));
    if (hit) {
      if (buf) parts.push(buf);
      buf = "";
      parts.push({ term: hit, text: hit });
      seen.add(hit);
      i += hit.length;
    } else {
      buf += text[i];
      i += 1;
    }
  }
  if (buf) parts.push(buf);
  return parts;
}
